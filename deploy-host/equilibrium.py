# равновесие: доход = еда + содержание
print("Предел колонии при разной ставке налога (еда+вода 1.22 кр/чел, содержание pop²×1e-6):")
for tax in (0.10, 0.15, 0.20, 0.25):
    p = (tax * 18 - 1.22) / 0.000001
    print(f"  налог {int(tax*100):>2}%: предел {p/1000:>7.0f} тыс. жителей | штраф счастья {'есть' if tax > 0.15 else 'нет'}")